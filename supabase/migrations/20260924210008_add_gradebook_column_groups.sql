-- ---------------------------------------------------------------------------
-- 3. Recovery of the implicit naming convention  --  ONE TIME PER GRADEBOOK
--
-- This function is the single place the slug heuristic is allowed to run, and it is a
-- recovery step, not a rule. The grouping instructors have been looking at was never
-- recorded anywhere, so the only surviving source for it is the slugs themselves. It reads
-- them once per gradebook and writes down what it finds. After that the convention stops
-- being load-bearing: nothing derives a group from a slug again.
--
-- There is deliberately NO trigger, NO view and NO generated column keeping groups in sync
-- with slugs. A group is whatever the rows say it is. This function only ever touches a
-- gradebook in which *nothing* is grouped yet, so it cannot silently re-group a gradebook
-- someone has since organised by hand -- re-running it is a no-op, not a reset.
--
-- It is called twice in the project's lifetime: once by the statement at the bottom of this
-- migration, for the gradebooks that already exist; and once per seeded class by
-- scripts/DatabaseSeedingUtils.ts, because `supabase db reset` replays migrations against an
-- empty database and the seeder then creates gradebooks that never existed when the backfill
-- above ran. Execute is granted to service_role only -- it is not a runtime API.
--
-- It reproduces gradebookTable.tsx:2556-2615 exactly, including the parts that are wrong:
--
--   * `assignment-<type>-*` groups as "assignment-<type>" only with 3+ hyphen parts, so
--     `assignment-final` (2 parts) files under "Assignment" rather than "Final".
--   * A gap in sort_order ends the run, so `quiz-1,quiz-2,[gap],quiz-4,quiz-5` becomes two
--     separate groups, both displaying "Quiz".
--   * A slug with no "-" groups under the whole slug ("attendance" -> "Attendance"), not
--     under "Other".
--   * "Other" is reached only by an empty slug or one starting with "-".
--
-- Unclassifiable rows: there are none, and that is the stated policy. Every column gets a
-- group, singletons included -- that is what the heuristic does, and the table simply
-- declines to draw a header for a group of one (gradebookTable.tsx:2894). Recording
-- singletons as NULL instead would be a different grouping, not the same one reproduced.
--
-- Ordering: columns are walked by (coalesce(sort_order,0), id). The memo sorts on
-- `sort_order ?? 0` with a stable sort, so its tiebreak is whatever order the client happened
-- to fetch rows in, which is not reproducible in SQL. `id` is an explicit, deterministic
-- stand-in. No seeded gradebook has a tie, so it cannot change the result here; on production
-- data it makes the outcome defined rather than incidental.
-- ---------------------------------------------------------------------------

create or replace function public.backfill_gradebook_column_groups(p_class_id bigint default null)
returns integer
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
    v_groups_created integer;
begin
    with targets as (
        -- Only gradebooks in which nothing is grouped yet.
        select c.gradebook_id
        from public.gradebook_columns c
        where p_class_id is null or c.class_id = p_class_id
        group by c.gradebook_id
        having count(c.group_id) = 0
    ),
    walked as (
        select
            c.id,
            c.class_id,
            c.gradebook_id,
            case
                when split_part(c.slug, '-', 1) = 'assignment'
                     and array_length(string_to_array(c.slug, '-'), 1) >= 3
                then split_part(c.slug, '-', 1) || '-' || split_part(c.slug, '-', 2)
                when split_part(c.slug, '-', 1) = '' then 'other'
                else split_part(c.slug, '-', 1)
            end as base_group_name,
            coalesce(c.sort_order, 0) as effective_sort_order,
            lag(coalesce(c.sort_order, 0)) over w as prev_sort_order,
            lag(
                case
                    when split_part(c.slug, '-', 1) = 'assignment'
                         and array_length(string_to_array(c.slug, '-'), 1) >= 3
                    then split_part(c.slug, '-', 1) || '-' || split_part(c.slug, '-', 2)
                    when split_part(c.slug, '-', 1) = '' then 'other'
                    else split_part(c.slug, '-', 1)
                end
            ) over w as prev_base_group_name
        from public.gradebook_columns c
        join targets t on t.gradebook_id = c.gradebook_id
        window w as (partition by c.gradebook_id order by coalesce(c.sort_order, 0), c.id)
    ),
    flagged as (
        -- A new group starts on the first column of a gradebook, on a break in sort_order
        -- contiguity, or on a change of base group name. The memo's three conditions.
        select
            walked.*,
            case
                when prev_sort_order is null then 1
                when effective_sort_order <> prev_sort_order + 1 then 1
                when base_group_name <> prev_base_group_name then 1
                else 0
            end as starts_group
        from walked
    ),
    numbered as (
        -- The memo's `currentGroupIndex`: a per-gradebook counter that increments on every
        -- new group and is never reset, which is what makes the keys unique per gradebook.
        select
            flagged.*,
            sum(starts_group) over (
                partition by gradebook_id
                order by effective_sort_order, id
                rows between unbounded preceding and current row
            ) as group_index
        from flagged
    ),
    keyed as (
        select
            numbered.*,
            base_group_name || '-' || group_index::text as group_key,
            case
                when base_group_name = 'other' then 'Other'
                -- charAt(0).toUpperCase() + slice(1): only the first character changes.
                -- initcap() would also lower-case the rest, which the memo does not do.
                when base_group_name like 'assignment-%'
                    then upper(left(split_part(base_group_name, '-', 2), 1))
                         || substr(split_part(base_group_name, '-', 2), 2)
                else upper(left(base_group_name, 1)) || substr(base_group_name, 2)
            end as display_name
        from numbered
    ),
    inserted as (
        insert into public.gradebook_column_groups (class_id, gradebook_id, group_key, name, sort_order)
        select
            min(class_id),
            gradebook_id,
            group_key,
            min(display_name),
            min(effective_sort_order)
        from keyed
        group by gradebook_id, group_key
        returning id, gradebook_id, group_key
    ),
    assigned as (
        update public.gradebook_columns c
        set group_id = inserted.id
        from keyed, inserted
        where keyed.id = c.id
          and inserted.gradebook_id = keyed.gradebook_id
          and inserted.group_key = keyed.group_key
        returning c.id
    )
    select count(*) into v_groups_created from inserted;

    return coalesce(v_groups_created, 0);
end;
$function$;

comment on function public.backfill_gradebook_column_groups(bigint) is
    'One-time recovery of the implicit slug-prefix grouping convention, for gradebooks that have no groups yet. Called by the migration that introduced gradebook_column_groups and by the seeder. Not a runtime API and not kept in sync with slugs: after it runs, a group is whatever the rows say it is.';

revoke all on function public.backfill_gradebook_column_groups(bigint) from public;
revoke all on function public.backfill_gradebook_column_groups(bigint) from anon;
revoke all on function public.backfill_gradebook_column_groups(bigint) from authenticated;
grant execute on function public.backfill_gradebook_column_groups(bigint) to service_role;

-- The one-time statement, for gradebooks that exist at the moment this migration runs. On a
-- `supabase db reset` there are none, and the seeder calls the same function afterwards.
select public.backfill_gradebook_column_groups();

