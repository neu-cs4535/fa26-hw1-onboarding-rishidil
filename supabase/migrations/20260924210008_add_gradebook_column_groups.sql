-- Gradebook column groups.
--
-- Until now, "which columns belong together" was not stored anywhere. The gradebook table
-- derived it at render time in the `groupedColumns` memo
-- (app/course/[course_id]/manage/gradebook/gradebookTable.tsx) by splitting `slug` on "-",
-- taking a prefix, and breaking the run wherever `sort_order` stopped being contiguous.
--
-- This migration makes a group a row. Membership is stored on the column, not recomputed.
--
-- Schema + RLS + backfill are one file because they are one change: the table is useless
-- without the policies, and a gradebook that comes out of this migration ungrouped is a
-- regression. Splitting them would let a deploy stop halfway in a state we never test.

-- ---------------------------------------------------------------------------
-- 1. Schema
-- ---------------------------------------------------------------------------

create table "public"."gradebook_column_groups" (
    "id" bigint generated by default as identity not null,
    "created_at" timestamp with time zone not null default now(),
    "class_id" bigint not null,
    "gradebook_id" bigint not null,
    -- Stable identity for the group within its gradebook. Backfilled with the key the
    -- render-time heuristic used to synthesise ("quiz-4", "skill-6"). It is an opaque
    -- identifier, not a slug: the digit is a per-gradebook group counter, not a column
    -- number. Nothing parses it.
    "group_key" text not null,
    -- What the header shows. Deliberately NOT unique per gradebook: the grouping this
    -- migration reproduces contains two distinct groups both displaying "Quiz" (the
    -- `quiz-3` column was deleted, which split the run in two). A uniqueness constraint
    -- here would make the correct answer impossible to store.
    "name" text not null,
    -- Left-to-right position: the smallest sort_order among the group's columns.
    "sort_order" integer not null
);

alter table "public"."gradebook_column_groups" add constraint "gradebook_column_groups_pkey"
    primary key ("id");

-- One group per key per gradebook.
create unique index "gradebook_column_groups_gradebook_id_group_key_key"
    on "public"."gradebook_column_groups" ("gradebook_id", "group_key");

-- Exists only to be the target of the composite foreign key from gradebook_columns below.
-- It is what makes "a column in another gradebook's group" unrepresentable rather than
-- merely unlikely.
create unique index "gradebook_column_groups_id_gradebook_id_key"
    on "public"."gradebook_column_groups" ("id", "gradebook_id");

-- Same trick one level up: pins a group's class_id to its gradebook's class_id, so a group
-- cannot claim to belong to a class its gradebook does not belong to.
create unique index if not exists "gradebooks_id_class_id_key"
    on "public"."gradebooks" ("id", "class_id");

alter table "public"."gradebook_column_groups" add constraint "gradebook_column_groups_gradebook_id_class_id_fkey"
    foreign key ("gradebook_id", "class_id")
    references "public"."gradebooks" ("id", "class_id") on delete cascade;

alter table "public"."gradebook_column_groups" add constraint "gradebook_column_groups_class_id_fkey"
    foreign key ("class_id") references "public"."classes" ("id") on delete cascade;

-- The RLS predicates below are both class_id-scoped; without this every policy check is a
-- sequential scan once more than one course exists.
create index "idx_gradebook_column_groups_class_id"
    on "public"."gradebook_column_groups" ("class_id");

create index "idx_gradebook_column_groups_gradebook_id"
    on "public"."gradebook_column_groups" ("gradebook_id");

-- Membership lives on the column: many columns to one group.
-- Nullable on purpose. A column created after this migration has no group until something
-- assigns one, and a NOT NULL here would mean either inventing a group at insert time (the
-- slug heuristic again, which is what we are removing) or breaking column creation.
alter table "public"."gradebook_columns" add column "group_id" bigint;

-- The composite key, not a plain FK on group_id alone: it forces the column's own
-- gradebook_id to equal the group's. A column can only ever point at a group in its own
-- gradebook. NULL group_id skips the check (MATCH SIMPLE), which is what we want.
alter table "public"."gradebook_columns" add constraint "gradebook_columns_group_id_gradebook_id_fkey"
    foreign key ("group_id", "gradebook_id")
    references "public"."gradebook_column_groups" ("id", "gradebook_id") on delete set null;

create index "idx_gradebook_columns_group_id"
    on "public"."gradebook_columns" ("group_id");

